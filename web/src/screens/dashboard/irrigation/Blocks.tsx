          <StatusBadge value={b.archivedAt ? 'INACTIVE' : b.status} label={b.archivedAt ? 'Archived' : undefined} />
          {can('irrigation', 'EDIT') && !b.archivedAt && <button type="button" className="btn-secondary" onClick={() => setEditing(true)}>Edit</button>}
          {can('irrigation', 'DELETE') && !b.archivedAt && <button type="button" className="btn-secondary" onClick={() => setArchiveOpen(true)}>Archive</button>}
