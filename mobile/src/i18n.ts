export type TranslationKey = keyof typeof en;

const dictionaries: Record<Language, Record<TranslationKey, string>> = { en, sw };

export function translate(language: Language, key: TranslationKey, vars?: Vars): string {
  const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

export function useI18n() {
  const language = useLanguageStore((state) => state.language);
  const setLanguage = useLanguageStore((state) => state.setLanguage);
  return {
    language,
    setLanguage,
    t: (key: TranslationKey, vars?: Vars) => translate(language, key, vars),
  };
}

export function prettyEnum(value: string): string {
  return value
    .split('_')
    .map((word) => (word === 'ID' ? 'ID' : word.charAt(0) + word.slice(1).toLowerCase()))
    .join(' ');
}

export function timeAgo(iso: string, t: (key: TranslationKey, vars?: Vars) => string): string {
  const diff = Date.now() - new Date(iso).getTime();
  const minutes = Math.floor(diff / 60000);
  if (minutes < 1) return t('justNow');
  if (minutes < 60) return t('minutesAgo', { value: minutes });
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return t('hoursAgo', { value: hours });
  return t('daysAgo', { value: Math.floor(hours / 24) });
}
